#!/bin/zsh
# writes js/frames-manifest.js from the extracted frame folders
cd ${0:a:h}/..
{ echo "// generated by _hf/manifest.sh — frame count per clip (assets/frames/<clip>/full/NNNN.webp)"; echo "export default {"
  for d in assets/frames/*/; do n=$(ls $d/full | wc -l | tr -d ' '); echo "  '$(basename $d)': $n,"; done; echo "};"; } > js/frames-manifest.js
